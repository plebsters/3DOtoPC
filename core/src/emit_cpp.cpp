// emit_cpp.cpp - turns analyzed blocks into C++ source.
//
// Every guest instruction becomes a call, with constant arguments, to the
// handler for its kind in tdort/arm_exec.h (the same code the interpreter
// runs). The kind and the condition are known here, so the generated code
// calls that handler directly instead of the whole decoder: the handlers are
// force-inlined, and the compiler has far less to wade through (Visual Studio
// took 10-30 minutes a game with the decoder inlined at every instruction).
#include "tdo/recomp.h"
#include "tdort/memory.h"
#include "tdort/arm_isa.h"
#include <cstdio>
#include <filesystem>
#include <fstream>

namespace fs = std::filesystem;

namespace tdo {
using tdort::load_be32;

static std::string hex8(uint32_t v) { char b[16]; std::snprintf(b, sizeof b, "%08X", v); return b; }

// An address in generated code: a constant, or for a program loaded at run
// time (a module) an offset from where it was loaded (B, set per call).
static std::string addr(uint32_t a, bool rel) { return rel ? "(B + 0x" + hex8(a) + "u)" : "0x" + hex8(a) + "u"; }

// One guest instruction as a C++ statement that returns when it changes pc.
// With `rel`, pc is an offset from the module's load address.
static std::string emit_insn(uint32_t i, uint32_t pc, bool rel = false) {
    using tdort::Op;
    const std::string I = "0x" + hex8(i) + "u", P = addr(pc, rel);
    const uint32_t cond = tdort::cond_of(i);
    if (cond == 0xF) return "if (exec(c, " + I + ", " + P + ")) return;";   // never-execute space: leave to exec()
    std::string call;
    switch (tdort::classify(i)) {
    case Op::DataProc:   call = "exec_dataproc(c, " + I + ", " + P + ")"; break;
    case Op::Mul:        call = "exec_mul(c, " + I + ")"; break;
    case Op::Swp:        call = "exec_swp(c, " + I + ")"; break;
    case Op::SingleXfer: call = "exec_single(c, " + I + ", " + P + ")"; break;
    case Op::HalfXfer:   call = "exec_half(c, " + I + ", " + P + ")"; break;
    case Op::BlockXfer:  call = "exec_block(c, " + I + ", " + P + ")"; break;
    case Op::Branch: {
        std::string body = "{ ";
        if (i & 0x01000000) body += "c->r[14] = " + addr(pc + 4, rel) + "; ";
        body += "c->r[15] = " + addr(tdort::branch_target(i, pc), rel) + "; return; }";
        return cond == 0xE ? body : "if (cond_pass(c, " + std::to_string(cond) + "u)) " + body;
    }
    default:             return "if (exec(c, " + I + ", " + P + ")) return;";   // MRS, MSR, SWI, undefined
    }
    return cond == 0xE ? "if (" + call + ") return;"
                       : "if (cond_pass(c, " + std::to_string(cond) + "u) && " + call + ") return;";
}

static std::string c_escape(const std::string& s) {
    std::string o;
    for (char ch : s) {
        if (ch == '"' || ch == '\\') { o += '\\'; o += ch; }
        else if ((unsigned char)ch < 0x20) o += ' ';
        else o += ch;
    }
    return o;
}

// fnv1a-32 of a block's instruction words: the runtime compares it with the
// program in memory before running the translated block.
static uint32_t block_check(const tdort::AifImage& img, const Block& b) {
    uint32_t h = 2166136261u;
    for (uint32_t k = 0; k < b.count * 4; ++k) { h ^= img.bytes[b.start - img.image_base + k]; h *= 16777619u; }
    return h;
}

// Programs the game loads at run time: translated once, run wherever they land.
static void emit_module(const ModuleSource& m, size_t k, uint32_t per, const std::string& out_dir,
                        std::vector<std::string>& files, std::ofstream& t) {
    std::vector<const Block*> blocks;
    for (auto& kv : m.analysis.blocks) blocks.push_back(&kv.second);
    const tdort::AifImage& img = m.image;
    const std::string pre = "tdo_m" + std::to_string(k) + "_";
    for (size_t f = 0, idx = 0; idx < blocks.size(); ++f) {
        std::string name = "mod" + std::to_string(k) + "_" + std::to_string(f) + ".cpp";
        std::ofstream o(fs::u8path(out_dir) / name);
        o << "// Generated by 3DO to PC from " << c_escape(m.name) << ". Do not edit.\n"
             "#include \"tdort/arm_exec.h\"\n"
             "using namespace tdort;\n\n";
        for (uint32_t n = 0; n < per && idx < blocks.size(); ++n, ++idx) {
            const Block& b = *blocks[idx];
            const uint32_t off = b.start - img.image_base;
            o << "void " << pre << hex8(off) << "(Cpu* c) {\n";
            o << "    const uint32_t B = c->mod_base;\n";
            o << "    c->cycles += " << b.count << ";\n";
            for (uint32_t q = 0; q < b.count; ++q) {
                uint32_t i = load_be32(&img.bytes[off + 4 * q]);
                o << "    " << emit_insn(i, off + 4 * q, true) << "  // " << disasm(i, off + 4 * q) << "\n";
            }
            o << "    c->r[15] = B + 0x" << hex8(off + 4 * b.count) << "u;\n}\n\n";
        }
        files.push_back(name);
    }
    for (auto* b : blocks) t << "void " << pre << hex8(b->start - img.image_base) << "(tdort::Cpu*);\n";
    t << "static const tdort::ModuleEntry " << pre << "entries[] = {\n";
    for (auto* b : blocks)
        t << "    {0x" << hex8(b->start - img.image_base) << "u, " << b->count * 4 << "u, 0x" << hex8(block_check(img, *b))
          << "u, " << pre << hex8(b->start - img.image_base) << "},\n";
    if (blocks.empty()) t << "    {0u, 0u, 0u, nullptr},\n";
    t << "};\n";
}

std::vector<std::string> emit_cpp(const tdort::AifImage& img, const Analysis& a,
                                  const EmitOptions& opt, const std::string& out_dir,
                                  const std::vector<ModuleSource>& modules) {
    std::vector<std::string> files;
    fs::create_directories(fs::u8path(out_dir));
    {   // sources from an earlier conversion would be built too (the game's CMake globs src/*.cpp)
        std::error_code ec;
        for (auto& e : fs::directory_iterator(fs::u8path(out_dir), ec))
            if (e.path().extension() == ".cpp") fs::remove(e.path(), ec);
    }
    std::vector<const Block*> blocks;
    for (auto& kv : a.blocks) blocks.push_back(&kv.second);

    const uint32_t per = opt.blocks_per_file ? opt.blocks_per_file : 250;
    for (size_t f = 0, idx = 0; idx < blocks.size() || (f == 0 && blocks.empty()); ++f) {
        if (blocks.empty()) break;
        std::string name = "recomp_" + std::to_string(f) + ".cpp";
        std::ofstream o(fs::u8path(out_dir) / name);
        o << "// Generated by 3DO to PC. Do not edit: re-run the converter instead.\n"
             "#include \"tdort/arm_exec.h\"\n"
             "using namespace tdort;\n\n";
        for (uint32_t n = 0; n < per && idx < blocks.size(); ++n, ++idx) {
            const Block& b = *blocks[idx];
            o << "// " << disasm(load_be32(&img.bytes[b.start - img.image_base]), b.start) << " ...\n";
            o << "void tdo_b_" << hex8(b.start) << "(Cpu* c) {\n";
            o << "    c->cycles += " << b.count << ";\n";
            for (uint32_t k = 0; k < b.count; ++k) {
                uint32_t pc = b.start + 4 * k;
                uint32_t i = load_be32(&img.bytes[pc - img.image_base]);
                o << "    " << emit_insn(i, pc) << "  // " << disasm(i, pc) << "\n";
            }
            o << "    c->r[15] = 0x" << hex8(b.start + 4 * b.count) << "u;\n}\n\n";
        }
        files.push_back(name);
    }

    std::ofstream t(fs::u8path(out_dir) / "recomp_table.cpp");
    t << "// Generated by 3DO to PC.\n#include \"tdort/runtime.h\"\n\n";
    for (auto* b : blocks) t << "void tdo_b_" << hex8(b->start) << "(tdort::Cpu*);\n";
    t << "\nextern \"C\" const tdort::RecompEntry tdort_recomp_table[] = {\n";
    for (auto* b : blocks)
        t << "    {0x" << hex8(b->start) << "u, " << b->count * 4 << "u, tdo_b_" << hex8(b->start) << "},\n";
    if (blocks.empty()) t << "    {0u, 0u, nullptr},\n";
    t << "};\n";
    t << "extern \"C\" const uint32_t tdort_recomp_count = " << blocks.size() << "u;\n";
    t << "extern \"C\" const char tdort_image_hash[] = \"" << tdort::fnv1a64_hex(img.bytes) << "\";\n";
    t << "extern \"C\" const char tdort_game_name[] = \"" << c_escape(opt.game_name) << "\";\n";
    t << "extern \"C\" const uint32_t tdort_image_base = 0x" << hex8(img.image_base) << "u;\n\n";
    for (size_t k = 0; k < modules.size(); ++k) emit_module(modules[k], k, per, out_dir, files, t);
    t << "\nextern \"C\" const tdort::ModuleInfo tdort_modules[] = {\n";
    for (size_t k = 0; k < modules.size(); ++k) {
        const ModuleSource& m = modules[k];
        t << "    {\"" << c_escape(m.name) << "\", \"" << m.file_hash << "\", 0x" << hex8(m.image.entry - m.image.image_base)
          << "u, " << m.analysis.blocks.size() << "u, tdo_m" << k << "_entries},\n";
    }
    if (modules.empty()) t << "    {\"\", \"\", 0u, 0u, nullptr},\n";
    t << "};\n";
    t << "extern \"C\" const uint32_t tdort_module_count = " << modules.size() << "u;\n";
    files.push_back("recomp_table.cpp");
    return files;
}

} // namespace tdo
